"""Make xpi/lib/skai_memory.js (a classic script defining SkaiMemory) from the ES-module skai_memory.js
of the sk_notes repository: python3 tools/make_memory_lib.py <path to skai_memory.js>"""
import re, sys
src = open(sys.argv[1], encoding="utf-8").read()
body = re.sub(r"^export default Memory;\n", "", src, flags=re.M)
body = re.sub(r"^export (async function|function|class|const)", r"\1", body, flags=re.M)
# the Node-only default file access (dynamic imports, import.meta) cannot live in a classic script
a = body.index("    const nfs = await import(")
b = body.index("    return this._fs;")
body = body[:a] + "    throw new Error('pass { fs } to Memory outside Node');\n" + body[b:]
open("xpi/lib/skai_memory.js", "w", encoding="utf-8").write(
    "/* Generated by tools/make_memory_lib.py from skai_memory.js (sk_notes repository): do not edit. */\n"
    "(function () {\n" + body + "\nglobalThis.SkaiMemory = { Memory, slug, edgeStyle, DEFAULT_DIR };\n})();\n")
